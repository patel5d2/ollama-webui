#!/usr/bin/env python3
"""Aggregate measured runs into the report tables and one comparison chart."""
import csv, json, pathlib, statistics
import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = pathlib.Path(__file__).resolve().parent
RESULTS = ROOT / 'results'

def load():
    runs = []
    for d in sorted(RESULTS.iterdir()):
        csv_path = d / 'measurements.csv'
        if csv_path.exists():
            rows = list(csv.DictReader(csv_path.open()))
            if rows:
                runs.append((d.name, rows))
    return runs

def f(row, key):
    v = row[key]
    return float(v) if v not in ('', None) else None

# Latest complete five-prompt baseline suite per (environment, model).
baseline, settings = {}, {}
for name, rows in load():
    for row in rows:
        key = (row['environment'], row['model'])
        if row['condition'] == 'baseline':
            baseline.setdefault(key, {}).setdefault(name, []).append(row)
        else:
            settings.setdefault(key, {}).setdefault(name, []).append(row)

def pick(store):
    out = {}
    for key, byrun in store.items():
        complete = [(n, r) for n, r in sorted(byrun.items()) if len(r) >= 5] or sorted(byrun.items())
        out[key] = complete[-1]
    return out

chosen, chosen_settings = pick(baseline), pick(settings)

lines = ['# Measured results (generated by analyze.py)\n']
lines.append('## Baseline suites — five fixed prompts per model\n')
lines.append('| Environment | Model | Params | Quant | Run | Prompts | Load s | Median answer s | Median tokens/s | Model alloc MiB | GPU alloc MiB |')
lines.append('|---|---|---|---|---|---|---|---|---|---|---|')
summary = {}
for (env, model), (run, rows) in sorted(chosen.items()):
    ans = [f(r, 'answer_wall_s') for r in rows]
    tps = [f(r, 'tokens_per_second') for r in rows if f(r, 'tokens_per_second')]
    alloc = f(rows[0], 'model_allocation_bytes') or 0
    vram = f(rows[0], 'gpu_allocation_bytes') or 0
    load = f(rows[0], 'load_wall_s')
    summary[(env, model)] = dict(answer=statistics.median(ans), tps=statistics.median(tps),
                                 load=load, alloc=alloc, vram=vram, n=len(rows))
    lines.append(f"| {env} | {model} | {rows[0]['parameter_size']} | {rows[0]['quantization']} | {run} | "
                 f"{len(rows)} | {load:.2f} | {statistics.median(ans):.2f} | {statistics.median(tps):.1f} | "
                 f"{alloc/2**20:.0f} | {vram/2**20:.0f} |")

lines.append('\n## Settings experiment — qwen3:1.7b on P1\n')
lines.append('| Environment | Condition | Temperature | num_predict | Answer s | Tokens/s | Output tokens | done_reason |')
lines.append('|---|---|---|---|---|---|---|---|')
for (env, model), (run, rows) in sorted(chosen_settings.items()):
    for r in rows:
        lines.append(f"| {env} | {r['condition']} | {r['temperature']} | {r['num_predict']} | "
                     f"{f(r,'answer_wall_s'):.2f} | {f(r,'tokens_per_second'):.1f} | {r['output_tokens']} | {r['done_reason']} |")

(ROOT / 'RESULTS.md').write_text('\n'.join(lines) + '\n')

# Chart: generation speed per model per environment.
models = sorted({m for _, m in summary})
envs = sorted({e for e, _ in summary})
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))
width = 0.8 / len(envs)
for i, env in enumerate(envs):
    xs = [j + i * width for j in range(len(models))]
    ax1.bar(xs, [summary.get((env, m), {}).get('tps', 0) for m in models], width, label=env)
    ax2.bar(xs, [summary.get((env, m), {}).get('answer', 0) for m in models], width, label=env)
for ax, title, ylab in ((ax1, 'Generation speed (higher is better)', 'median tokens/s'),
                        (ax2, 'Answer latency (lower is better)', 'median seconds per prompt')):
    ax.set_xticks([j + width * (len(envs) - 1) / 2 for j in range(len(models))])
    ax.set_xticklabels(models, fontsize=8)
    ax.set_title(title, fontsize=10); ax.set_ylabel(ylab, fontsize=9); ax.legend(fontsize=8)
fig.suptitle('Same five prompts, same settings, three environments', fontsize=11)
fig.tight_layout()
fig.savefig(ROOT / 'comparison.png', dpi=150)
print((ROOT / 'RESULTS.md').read_text())
print('wrote', ROOT / 'comparison.png')
